FROM FOOD_INSPECTIONS_RAW;

-- Verifica que los identificadores sigan siendo únicos
SELECT COUNT(DISTINCT INSPECTION_ID) AS IDS_UNICOS
FROM FOOD_INSPECTIONS_RAW;



-- Resume las principales validaciones entre RAW y CLEAN
SELECT 'Filas RAW' AS VALIDACION, COUNT(*) AS VALOR
FROM FOOD_INSPECTIONS_RAW

UNION ALL

SELECT 'Filas CLEAN', COUNT(*)
FROM FOOD_INSPECTIONS_CLEAN

UNION ALL

SELECT 'IDs unicos RAW', COUNT(DISTINCT INSPECTION_ID)
FROM FOOD_INSPECTIONS_RAW

UNION ALL

SELECT 'IDs unicos CLEAN', COUNT(DISTINCT INSPECTION_ID)
FROM FOOD_INSPECTIONS_CLEAN

UNION ALL

SELECT 'FACILITY_TYPE RAW', COUNT(DISTINCT FACILITY_TYPE)
FROM FOOD_INSPECTIONS_RAW

UNION ALL

SELECT 'FACILITY_TYPE CLEAN', COUNT(DISTINCT FACILITY_TYPE)
FROM FOOD_INSPECTIONS_CLEAN

UNION ALL

SELECT 'INSPECTION_TYPE RAW', COUNT(DISTINCT INSPECTION_TYPE)
FROM FOOD_INSPECTIONS_RAW

UNION ALL

SELECT 'INSPECTION_TYPE CLEAN', COUNT(DISTINCT INSPECTION_TYPE)
FROM FOOD_INSPECTIONS_CLEAN

UNION ALL

SELECT 'VIOLATIONS > 4000 RAW', COUNT(*)
FROM FOOD_INSPECTIONS_RAW
WHERE DBMS_LOB.GETLENGTH(VIOLATIONS) > 4000

UNION ALL

SELECT 'VIOLATIONS > 4000 CLEAN', COUNT(*)
FROM FOOD_INSPECTIONS_CLEAN
WHERE DBMS_LOB.GETLENGTH(VIOLATIONS) > 4000

UNION ALL

SELECT 'Maximo VIOLATIONS RAW', MAX(DBMS_LOB.GETLENGTH(VIOLATIONS))
FROM FOOD_INSPECTIONS_RAW

UNION ALL

SELECT 'Maximo VIOLATIONS CLEAN', MAX(DBMS_LOB.GETLENGTH(VIOLATIONS))
FROM FOOD_INSPECTIONS_CLEAN;

