-- Data Analytics: asociaciones con una mayor proporcion de Fail.
-- Porcentaje = Fail / todas las inspecciones del grupo * 100.

-- 1. Revisa los resultados incluidos en el denominador.
SELECT RESULTS, COUNT(*) AS TOTAL_INSPECCIONES
FROM FOOD_INSPECTIONS_CLEAN
GROUP BY RESULTS
ORDER BY TOTAL_INSPECCIONES DESC;

-- 2. Verifica identificadores, fechas y datos faltantes.
SELECT COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(DISTINCT INSPECTION_ID) AS ID_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS ID_NULOS,
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA,
       COUNT(*) - COUNT(INSPECTION_DATE) AS FECHAS_NULAS,
       COUNT(*) - COUNT(RISK) AS RISK_NULOS,
       COUNT(*) - COUNT(INSPECTION_TYPE) AS TIPO_INSPECCION_NULOS,
       COUNT(*) - COUNT(FACILITY_TYPE) AS TIPO_ESTABLECIMIENTO_NULOS
FROM FOOD_INSPECTIONS_CLEAN;

-- 3. Calcula el resultado general.
SELECT COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END) AS TOTAL_FAIL,
       ROUND(100.0 * COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END)
             / NULLIF(COUNT(*), 0), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_CLEAN;

-- 4. Compara RISK; conserva All y NULL por separado.
SELECT NVL(RISK, 'SIN DATO') AS RISK,
       COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END) AS TOTAL_FAIL,
       ROUND(100.0 * COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END)
             / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_CLEAN
GROUP BY NVL(RISK, 'SIN DATO')
ORDER BY PORCENTAJE_FAIL DESC, TOTAL_INSPECCIONES DESC;

-- 5. Compara tipos de inspeccion con al menos 1000 registros.
SELECT NVL(INSPECTION_TYPE, 'SIN DATO') AS INSPECTION_TYPE,
       COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END) AS TOTAL_FAIL,
       ROUND(100.0 * COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END)
             / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_CLEAN
GROUP BY NVL(INSPECTION_TYPE, 'SIN DATO')
HAVING COUNT(*) >= 1000
ORDER BY PORCENTAJE_FAIL DESC, TOTAL_INSPECCIONES DESC;

-- 6. Compara establecimientos con al menos 1000 inspecciones.
SELECT NVL(FACILITY_TYPE, 'SIN DATO') AS FACILITY_TYPE,
       COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END) AS TOTAL_FAIL,
       ROUND(100.0 * COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END)
             / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_CLEAN
GROUP BY NVL(FACILITY_TYPE, 'SIN DATO')
HAVING COUNT(*) >= 1000
ORDER BY PORCENTAJE_FAIL DESC, TOTAL_INSPECCIONES DESC;

-- 7. Compara los anos; el ultimo puede estar incompleto.
SELECT EXTRACT(YEAR FROM INSPECTION_DATE) AS ANO,
       COUNT(*) AS TOTAL_INSPECCIONES,
       COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END) AS TOTAL_FAIL,
       ROUND(100.0 * COUNT(CASE WHEN RESULTS = 'Fail' THEN 1 END)
             / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_CLEAN
GROUP BY EXTRACT(YEAR FROM INSPECTION_DATE)
ORDER BY ANO;
