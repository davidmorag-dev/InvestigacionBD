-- 1. Crea una vista de lectura sin modificar CLEAN.
CREATE OR REPLACE VIEW FOOD_INSPECTIONS_SCIENCE AS
SELECT RISK,
       FACILITY_TYPE,
       ZIP,
       EXTRACT(MONTH FROM INSPECTION_DATE) AS MES,
       EXTRACT(YEAR FROM INSPECTION_DATE) AS ANO,
       CASE WHEN RESULTS = 'Fail' THEN 1 ELSE 0 END AS FAIL
FROM FOOD_INSPECTIONS_CLEAN
WHERE RESULTS IN ('Fail', 'Pass', 'Pass w/ Conditions')
  AND (INSPECTION_TYPE IS NULL OR INSPECTION_TYPE <> 'NON-INSPECTION')
  AND INSPECTION_DATE >= DATE '2019-01-01'
  AND INSPECTION_DATE < DATE '2026-01-01'
WITH READ ONLY;

-- 2. Cuenta el total, Fail y No Fail de la vista.
SELECT COUNT(*) AS TOTAL,
       SUM(FAIL) AS TOTAL_FAIL,
       COUNT(*) - SUM(FAIL) AS TOTAL_NO_FAIL,
       ROUND(100.0 * SUM(FAIL) / NULLIF(COUNT(*), 0), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_SCIENCE;

-- 3. Compara entrenamiento y prueba por periodo.
SELECT CASE WHEN ANO <= 2024 THEN 'TRAIN 2019-2024'
            ELSE 'TEST 2025' END AS PERIODO,
       COUNT(*) AS TOTAL,
       SUM(FAIL) AS TOTAL_FAIL,
       COUNT(*) - SUM(FAIL) AS TOTAL_NO_FAIL,
       ROUND(100.0 * SUM(FAIL) / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_SCIENCE
GROUP BY CASE WHEN ANO <= 2024 THEN 'TRAIN 2019-2024'
              ELSE 'TEST 2025' END
ORDER BY MIN(ANO);

-- 4. Revisa la distribucion anual.
SELECT ANO, COUNT(*) AS TOTAL, SUM(FAIL) AS TOTAL_FAIL,
       ROUND(100.0 * SUM(FAIL) / COUNT(*), 2) AS PORCENTAJE_FAIL
FROM FOOD_INSPECTIONS_SCIENCE
GROUP BY ANO
ORDER BY ANO;

-- 5. Revisa faltantes y categorias de las predictoras.
SELECT COUNT(*) - COUNT(RISK) AS RISK_NULOS,
       COUNT(DISTINCT RISK) AS RISK_CATEGORIAS,
       COUNT(*) - COUNT(FACILITY_TYPE) AS FACILITY_NULOS,
       COUNT(DISTINCT FACILITY_TYPE) AS FACILITY_CATEGORIAS,
       COUNT(*) - COUNT(ZIP) AS ZIP_NULOS,
       COUNT(DISTINCT ZIP) AS ZIP_CATEGORIAS,
       COUNT(*) - COUNT(MES) AS MES_NULOS,
       COUNT(DISTINCT MES) AS MESES
FROM FOOD_INSPECTIONS_SCIENCE;

-- 6. Comprueba registros conservados y la exclusion de NON-INSPECTION.
SELECT COUNT(*) AS REGISTROS_CLEAN,
       COUNT(CASE WHEN RESULTS IN ('Fail', 'Pass', 'Pass w/ Conditions')
                        AND INSPECTION_DATE >= DATE '2019-01-01'
                        AND INSPECTION_DATE < DATE '2026-01-01'
                  THEN 1 END) AS ELEGIBLES_ANTES_EXCLUSION,
       COUNT(CASE WHEN RESULTS IN ('Fail', 'Pass', 'Pass w/ Conditions')
                        AND INSPECTION_DATE >= DATE '2019-01-01'
                        AND INSPECTION_DATE < DATE '2026-01-01'
                        AND INSPECTION_TYPE = 'NON-INSPECTION'
                  THEN 1 END) AS NON_INSPECTION_EXCLUIDOS
FROM FOOD_INSPECTIONS_CLEAN;
