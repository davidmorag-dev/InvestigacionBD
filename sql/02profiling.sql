-- 8. Revisa categorías y frecuencias de INSPECTION_TYPE
SELECT INSPECTION_TYPE, UPPER(TRIM(INSPECTION_TYPE)) AS VALOR_COMPARACION,
       COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
GROUP BY INSPECTION_TYPE
