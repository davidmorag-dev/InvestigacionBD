-- P25. Conversion decimal explicita y rangos geograficos
-- Acepta coma o punto decimal y signo, sin separadores de miles.
-- REPLACE unifica la representacion solo en la consulta; el modelo D y
-- NLS_NUMERIC_CHARACTERS fijan el punto decimal independientemente de la sesion.
-- Un formato no reconocido o conversion fallida se cuenta como invalido.
-- Los blancos y NULL se cuentan como ausencia, separados de la invalidez.
WITH TEXTOS AS (
    SELECT r.*, CASE WHEN REGEXP_LIKE(LATITUDE, '^[[:space:]]*$', 'c') THEN NULL
                ELSE TRIM(LATITUDE) END AS LAT_TEXTO,
           CASE WHEN REGEXP_LIKE(LONGITUDE, '^[[:space:]]*$', 'c') THEN NULL
                ELSE TRIM(LONGITUDE) END AS LON_TEXTO, CASE WHEN REGEXP_LIKE(LOCATION, '^[[:space:]]*$', 'c') THEN NULL
                ELSE TRIM(LOCATION) END AS LOC_TEXTO
    FROM FOOD_INSPECTIONS_RAW r
), NUMEROS AS (
    SELECT t.*,
       CASE WHEN REGEXP_LIKE(LAT_TEXTO, '^[+-]?[0-9]+([.,][0-9]+)?$', 'c')
            THEN TO_NUMBER(REPLACE(LAT_TEXTO, ',', '.') DEFAULT NULL ON CONVERSION ERROR,
                  '99999999999999999999D999999999999999999', 'NLS_NUMERIC_CHARACTERS=''.,''')
       END AS LAT_NUM,
       CASE WHEN REGEXP_LIKE(LON_TEXTO, '^[+-]?[0-9]+([.,][0-9]+)?$', 'c')
            THEN TO_NUMBER(REPLACE(LON_TEXTO, ',', '.') DEFAULT NULL ON CONVERSION ERROR,
                  '99999999999999999999D999999999999999999', 'NLS_NUMERIC_CHARACTERS=''.,''')
       END AS LON_NUM,
       CASE WHEN REGEXP_LIKE(LOC_TEXTO, '^[(][[:space:]]*[+-]?[0-9]+([.][0-9]+)?[[:space:]]*,[[:space:]]*[+-]?[0-9]+([.][0-9]+)?[[:space:]]*[)]$', 'c')
            THEN TO_NUMBER(REGEXP_SUBSTR(LOC_TEXTO, '[+-]?[0-9]+([.][0-9]+)?', 1, 1, 'c') DEFAULT NULL ON CONVERSION ERROR,
                  '99999999999999999999D999999999999999999', 'NLS_NUMERIC_CHARACTERS=''.,''')
       END AS LOC_LAT_NUM,
       CASE WHEN REGEXP_LIKE(LOC_TEXTO, '^[(][[:space:]]*[+-]?[0-9]+([.][0-9]+)?[[:space:]]*,[[:space:]]*[+-]?[0-9]+([.][0-9]+)?[[:space:]]*[)]$', 'c')
            THEN TO_NUMBER(REGEXP_SUBSTR(LOC_TEXTO, '[+-]?[0-9]+([.][0-9]+)?', 1, 2, 'c') DEFAULT NULL ON CONVERSION ERROR,
                  '99999999999999999999D999999999999999999', 'NLS_NUMERIC_CHARACTERS=''.,''')
       END AS LOC_LON_NUM
    FROM TEXTOS t
)
SELECT COUNT(*) AS TOTAL_REGISTROS,
       COUNT(CASE WHEN LAT_TEXTO IS NULL THEN 1 END) AS LAT_AUSENTE,
       COUNT(CASE WHEN LON_TEXTO IS NULL THEN 1 END) AS LON_AUSENTE,
       COUNT(CASE WHEN LOC_TEXTO IS NULL THEN 1 END) AS LOCATION_AUSENTE,
       COUNT(CASE WHEN LAT_TEXTO IS NOT NULL AND LAT_NUM IS NULL THEN 1 END)
           AS LAT_CONVERSION_INVALIDA,
       COUNT(CASE WHEN LON_TEXTO IS NOT NULL AND LON_NUM IS NULL THEN 1 END)
           AS LON_CONVERSION_INVALIDA,
       COUNT(CASE WHEN LAT_NUM NOT BETWEEN -90 AND 90 THEN 1 END)
           AS LAT_FUERA_RANGO,
       COUNT(CASE WHEN LON_NUM NOT BETWEEN -180 AND 180 THEN 1 END)
           AS LON_FUERA_RANGO,
       COUNT(CASE WHEN (LAT_TEXTO IS NOT NULL AND (LAT_NUM IS NULL OR LAT_NUM NOT BETWEEN -90 AND 90))
    OR (LON_TEXTO IS NOT NULL AND (LON_NUM IS NULL OR LON_NUM NOT BETWEEN -180 AND 180)) THEN 1 END)
           AS REGISTROS_COORD_INVALIDAS,
       COUNT(CASE WHEN
           (CASE WHEN LAT_TEXTO IS NOT NULL THEN 1 ELSE 0 END
            + CASE WHEN LON_TEXTO IS NOT NULL THEN 1 ELSE 0 END
            + CASE WHEN LOC_TEXTO IS NOT NULL THEN 1 ELSE 0 END) IN (1, 2)
