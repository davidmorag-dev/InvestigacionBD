-- P01. Configuracion de la sesion
-- Registra los parametros regionales para interpretar los resultados.
-- Las conversiones numericas de este archivo fijan su propio formato.
SELECT PARAMETER, VALUE
FROM NLS_SESSION_PARAMETERS
WHERE PARAMETER IN (
    'NLS_DATE_FORMAT', 'NLS_DATE_LANGUAGE', 'NLS_CALENDAR',
    'NLS_NUMERIC_CHARACTERS', 'NLS_COMP', 'NLS_SORT'
)
ORDER BY PARAMETER;

-- P02. Total de filas e identificadores distintos
-- Revalida las 316.961 filas documentadas y la unicidad de INSPECTION_ID.
-- COUNT(DISTINCT) no incluye NULL; por eso tambien se cuentan los ID nulos.
SELECT COUNT(*) AS TOTAL_REGISTROS,
       COUNT(INSPECTION_ID) AS ID_NO_NULOS,
       COUNT(DISTINCT INSPECTION_ID) AS ID_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS ID_NULOS,
       COUNT(INSPECTION_ID) - COUNT(DISTINCT INSPECTION_ID)
           AS REPETICIONES_ID_NO_NULOS
FROM FOOD_INSPECTIONS_RAW;

-- P03. Rango de fechas en formato ISO
-- Muestra las fechas realmente almacenadas, sin ambiguedad entre dia y mes.
-- El CSV revisado con MM/DD/YYYY abarca 2010-01-04 a 2026-10-09;
-- ese rango debe confirmarse en Oracle. La fecha de corte es la del CSV.
SELECT TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA,
       COUNT(*) - COUNT(INSPECTION_DATE) AS FECHAS_NULAS,
       COUNT(CASE WHEN INSPECTION_DATE < DATE '2010-01-01' THEN 1 END)
           AS ANTERIORES_A_2010,
       COUNT(CASE WHEN INSPECTION_DATE >= DATE '2026-10-11' THEN 1 END)
           AS POSTERIORES_AL_CORTE_CSV
FROM FOOD_INSPECTIONS_RAW;

-- P04. Contraste de fechas de dos inspecciones
-- Compara los ID 67757 y 2644019 con sus fechas en el CSV.
-- LEFT JOIN muestra tambien un ID ausente. NO compara texto ambiguo.
-- Una discrepancia requiere investigar carga o redaccion; no se corrige aqui.
WITH REFERENCIA_CSV AS (
    SELECT 67757 AS INSPECTION_ID, '01/04/2010' AS FECHA_TEXTO_CSV,
           DATE '2010-01-04' AS FECHA_ESPERADA
    FROM DUAL
    UNION ALL
    SELECT 2644019, '10/09/2026', DATE '2026-10-09'
    FROM DUAL
)
SELECT c.INSPECTION_ID, r.DBA_NAME, c.FECHA_TEXTO_CSV,
       TO_CHAR(c.FECHA_ESPERADA, 'YYYY-MM-DD') AS FECHA_ESPERADA_CSV,
       TO_CHAR(r.INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA_ORACLE,
       TO_CHAR(r.INSPECTION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS FECHA_Y_HORA,
       CASE
           WHEN r.INSPECTION_ID IS NULL THEN 'ID AUSENTE'
           WHEN r.INSPECTION_DATE IS NULL THEN 'FECHA NULA'
           WHEN TRUNC(r.INSPECTION_DATE) = c.FECHA_ESPERADA THEN 'COINCIDE'
           ELSE 'REVISAR DIFERENCIA'
       END AS VALIDACION
FROM REFERENCIA_CSV c
LEFT JOIN FOOD_INSPECTIONS_RAW r ON r.INSPECTION_ID = c.INSPECTION_ID
ORDER BY c.INSPECTION_ID, r.ROWID;

-- P05. Distribucion mensual de inspecciones
-- Permite revisar cobertura temporal y meses inesperados.
-- No interpreta cambios de frecuencia como errores sin mas evidencia.
SELECT TO_CHAR(TRUNC(INSPECTION_DATE, 'MM'), 'YYYY-MM') AS MES,
       COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
GROUP BY TRUNC(INSPECTION_DATE, 'MM')
ORDER BY TRUNC(INSPECTION_DATE, 'MM');

