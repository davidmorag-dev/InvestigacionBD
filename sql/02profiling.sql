       CASE WHEN VALOR IS NULL THEN '(NULL)'
            ELSE '[' || VALOR || ']' END AS VALOR_ORIGINAL_VISIBLE,
       LENGTH(VALOR) AS LONGITUD_ORIGINAL, CANTIDAD, ESCRITURAS_ORIGINALES
FROM VARIANTES
WHERE ESCRITURAS_ORIGINALES > 1
ORDER BY COLUMNA, VALOR_NORMALIZADO, CANTIDAD DESC, VALOR;

