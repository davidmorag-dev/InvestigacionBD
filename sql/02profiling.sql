-- P07. Ejemplos de cadenas formadas solo por espacios
-- Muestra hasta 100 casos en columnas VARCHAR2, delimitados por corchetes.
-- P06 y P29 cubren ademas el CLOB. El orden hace reproducible la muestra.
WITH TEXTOS AS (
    SELECT INSPECTION_ID, DBA_NAME, AKA_NAME, FACILITY_TYPE, RISK, ADDRESS, CITY, STATE, ZIP, INSPECTION_TYPE, RESULTS, LATITUDE, LONGITUDE, LOCATION
    FROM FOOD_INSPECTIONS_RAW
)
SELECT INSPECTION_ID, COLUMNA, '[' || VALOR || ']' AS VALOR_VISIBLE,
       LENGTH(VALOR) AS LONGITUD
FROM TEXTOS
UNPIVOT INCLUDE NULLS (VALOR FOR COLUMNA IN (
    DBA_NAME, AKA_NAME, FACILITY_TYPE, RISK, ADDRESS, CITY, STATE, ZIP, INSPECTION_TYPE, RESULTS, LATITUDE, LONGITUDE, LOCATION
))
WHERE VALOR IS NOT NULL
  AND REGEXP_LIKE(VALOR, '^[[:space:]]*$', 'c')
ORDER BY INSPECTION_ID, COLUMNA
FETCH FIRST 100 ROWS ONLY;

-- P08. Identificadores de inspeccion repetidos
-- Busca ID no nulos con mas de una fila. Los ID nulos se controlan en P02.
-- Un establecimiento puede tener muchas inspecciones con ID distintos.
SELECT INSPECTION_ID, COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
WHERE INSPECTION_ID IS NOT NULL
GROUP BY INSPECTION_ID
HAVING COUNT(*) > 1
ORDER BY CANTIDAD DESC, INSPECTION_ID;

-- P09. Resumen de duplicados exactos de contenido sin INSPECTION_ID
-- Agrupa primero columnas escalares y longitud para reducir candidatos.
-- DECODE compara tambien NULL con NULL. DBMS_LOB.COMPARE compara TODO el
-- CLOB, no solo sus primeros 4.000 caracteres. Se excluye solo INSPECTION_ID.
-- La fila representante es la menor FILA_ORACLE del contenido identico.
-- FILAS_ADICIONALES describe repeticiones; NO autoriza eliminarlas.
-- Referencia del CSV: 102 grupos y 112 filas adicionales; confirmar aqui.
WITH BASE AS (
    SELECT ROWIDTOCHAR(r.ROWID) AS FILA_ORACLE, r.*,
           DBMS_LOB.GETLENGTH(r.VIOLATIONS) AS LONGITUD_VIOLATIONS
    FROM FOOD_INSPECTIONS_RAW r
), AGRUPADOS AS (
    SELECT b.*, COUNT(*) OVER (PARTITION BY
        DBA_NAME, AKA_NAME, LICENSE_NUMBER, FACILITY_TYPE, RISK, ADDRESS, CITY, STATE, ZIP, INSPECTION_DATE, INSPECTION_TYPE, RESULTS, LATITUDE, LONGITUDE, LOCATION,
        LONGITUD_VIOLATIONS
    ) AS FILAS_CANDIDATAS
    FROM BASE b
), CANDIDATOS AS (
    SELECT * FROM AGRUPADOS WHERE FILAS_CANDIDATAS > 1
), COINCIDENCIAS AS (
    SELECT a.FILA_ORACLE, MIN(b.FILA_ORACLE) AS GRUPO_CONTENIDO
    FROM CANDIDATOS a
    JOIN CANDIDATOS b ON b.FILA_ORACLE <= a.FILA_ORACLE
    AND DECODE(a.DBA_NAME, b.DBA_NAME, 1, 0) = 1
    AND DECODE(a.AKA_NAME, b.AKA_NAME, 1, 0) = 1
    AND DECODE(a.LICENSE_NUMBER, b.LICENSE_NUMBER, 1, 0) = 1
    AND DECODE(a.FACILITY_TYPE, b.FACILITY_TYPE, 1, 0) = 1
    AND DECODE(a.RISK, b.RISK, 1, 0) = 1
    AND DECODE(a.ADDRESS, b.ADDRESS, 1, 0) = 1
    AND DECODE(a.CITY, b.CITY, 1, 0) = 1
    AND DECODE(a.STATE, b.STATE, 1, 0) = 1
    AND DECODE(a.ZIP, b.ZIP, 1, 0) = 1
    AND DECODE(a.INSPECTION_DATE, b.INSPECTION_DATE, 1, 0) = 1
    AND DECODE(a.INSPECTION_TYPE, b.INSPECTION_TYPE, 1, 0) = 1
    AND DECODE(a.RESULTS, b.RESULTS, 1, 0) = 1
    AND DECODE(a.LATITUDE, b.LATITUDE, 1, 0) = 1
    AND DECODE(a.LONGITUDE, b.LONGITUDE, 1, 0) = 1
    AND DECODE(a.LOCATION, b.LOCATION, 1, 0) = 1
    AND CASE
        WHEN a.VIOLATIONS IS NULL AND b.VIOLATIONS IS NULL THEN 1
        WHEN a.VIOLATIONS IS NOT NULL AND b.VIOLATIONS IS NOT NULL
             AND DBMS_LOB.COMPARE(a.VIOLATIONS, b.VIOLATIONS) = 0 THEN 1
        ELSE 0
    END = 1
    GROUP BY a.FILA_ORACLE
), GRUPOS_DUPLICADOS AS (
    SELECT GRUPO_CONTENIDO, COUNT(*) AS FILAS_GRUPO
    FROM COINCIDENCIAS
    GROUP BY GRUPO_CONTENIDO
    HAVING COUNT(*) > 1
)
SELECT COUNT(*) AS GRUPOS_CONTENIDO_REPETIDO,
       COALESCE(SUM(FILAS_GRUPO), 0) AS FILAS_EN_GRUPOS_REPETIDOS,
       COALESCE(SUM(FILAS_GRUPO - 1), 0) AS FILAS_ADICIONALES
FROM GRUPOS_DUPLICADOS;

-- P10. Pares con contenido identico e identificadores diferentes
-- Confirma el contenido completo y muestra cada par una sola vez.
-- P09 cuenta grupos y filas; el numero de pares de P10 es otra medida.
-- Los ID nulos y repetidos se revisan aparte en P02 y P08.
-- Esta consulta puede tardar mas que los conteos generales.
WITH BASE AS (
    SELECT ROWIDTOCHAR(r.ROWID) AS FILA_ORACLE, r.*,
           DBMS_LOB.GETLENGTH(r.VIOLATIONS) AS LONGITUD_VIOLATIONS
    FROM FOOD_INSPECTIONS_RAW r
), AGRUPADOS AS (
    SELECT b.*, COUNT(*) OVER (PARTITION BY
        DBA_NAME, AKA_NAME, LICENSE_NUMBER, FACILITY_TYPE, RISK, ADDRESS, CITY, STATE, ZIP, INSPECTION_DATE, INSPECTION_TYPE, RESULTS, LATITUDE, LONGITUDE, LOCATION,
        LONGITUD_VIOLATIONS
    ) AS FILAS_CANDIDATAS
    FROM BASE b
), CANDIDATOS AS (
    SELECT * FROM AGRUPADOS WHERE FILAS_CANDIDATAS > 1
)
SELECT a.INSPECTION_ID AS ID_A, b.INSPECTION_ID AS ID_B,
       a.FILA_ORACLE AS FILA_A, b.FILA_ORACLE AS FILA_B, a.DBA_NAME,
       a.LICENSE_NUMBER, TO_CHAR(a.INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA,
       a.INSPECTION_TYPE, a.RESULTS, a.LONGITUD_VIOLATIONS
FROM CANDIDATOS a
JOIN CANDIDATOS b ON a.FILA_ORACLE < b.FILA_ORACLE
    AND DECODE(a.DBA_NAME, b.DBA_NAME, 1, 0) = 1
    AND DECODE(a.AKA_NAME, b.AKA_NAME, 1, 0) = 1
    AND DECODE(a.LICENSE_NUMBER, b.LICENSE_NUMBER, 1, 0) = 1
    AND DECODE(a.FACILITY_TYPE, b.FACILITY_TYPE, 1, 0) = 1
    AND DECODE(a.RISK, b.RISK, 1, 0) = 1
    AND DECODE(a.ADDRESS, b.ADDRESS, 1, 0) = 1
    AND DECODE(a.CITY, b.CITY, 1, 0) = 1
    AND DECODE(a.STATE, b.STATE, 1, 0) = 1
    AND DECODE(a.ZIP, b.ZIP, 1, 0) = 1
    AND DECODE(a.INSPECTION_DATE, b.INSPECTION_DATE, 1, 0) = 1
    AND DECODE(a.INSPECTION_TYPE, b.INSPECTION_TYPE, 1, 0) = 1
    AND DECODE(a.RESULTS, b.RESULTS, 1, 0) = 1
    AND DECODE(a.LATITUDE, b.LATITUDE, 1, 0) = 1
    AND DECODE(a.LONGITUDE, b.LONGITUDE, 1, 0) = 1
    AND DECODE(a.LOCATION, b.LOCATION, 1, 0) = 1
    AND CASE
        WHEN a.VIOLATIONS IS NULL AND b.VIOLATIONS IS NULL THEN 1
        WHEN a.VIOLATIONS IS NOT NULL AND b.VIOLATIONS IS NOT NULL
             AND DBMS_LOB.COMPARE(a.VIOLATIONS, b.VIOLATIONS) = 0 THEN 1
        ELSE 0
    END = 1
