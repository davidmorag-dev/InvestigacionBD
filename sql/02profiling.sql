), VARIANTES AS (
    SELECT f.*, COUNT(*) OVER (
        PARTITION BY COLUMNA, VALOR_NORMALIZADO
    ) AS ESCRITURAS_ORIGINALES
    FROM FRECUENCIAS f
)
