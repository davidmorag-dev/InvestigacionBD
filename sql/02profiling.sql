-- 9. Detecta posibles duplicados por campos y longitud, sin confirmar igualdad del CLOB
SELECT DBA_NAME, LICENSE_NUMBER, ADDRESS,
       TO_CHAR(INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA,
       LENGTH(VIOLATIONS) AS LONGITUD_VIOLATIONS,
       COUNT(*) AS FILAS_COINCIDENTES,
       COUNT(DISTINCT INSPECTION_ID) AS ID_DISTINTOS,
       MIN(INSPECTION_ID) AS PRIMER_ID, MAX(INSPECTION_ID) AS ULTIMO_ID
FROM FOOD_INSPECTIONS_RAW
GROUP BY DBA_NAME, AKA_NAME, LICENSE_NUMBER, FACILITY_TYPE, RISK,
         ADDRESS, CITY, STATE, ZIP, INSPECTION_DATE, INSPECTION_TYPE,
         RESULTS, LATITUDE, LONGITUDE, LOCATION,
         LENGTH(VIOLATIONS)
HAVING COUNT(DISTINCT INSPECTION_ID) > 1
ORDER BY FILAS_COINCIDENTES DESC, PRIMER_ID;

-- 10. Revisa coordenadas faltantes, conversión decimal explícita y rangos válidos
WITH COORDENADAS AS (
    SELECT TRIM(LATITUDE) AS LAT_TEXTO, TRIM(LONGITUDE) AS LON_TEXTO,
           TO_NUMBER(REPLACE(TRIM(LATITUDE), ',', '.')
                     DEFAULT NULL ON CONVERSION ERROR,
                     '999999D999999999999999999',
                     'NLS_NUMERIC_CHARACTERS=''.,''') AS LAT_NUM,
           TO_NUMBER(REPLACE(TRIM(LONGITUDE), ',', '.')
                     DEFAULT NULL ON CONVERSION ERROR,
                     '999999D999999999999999999',
                     'NLS_NUMERIC_CHARACTERS=''.,''') AS LON_NUM
    FROM FOOD_INSPECTIONS_RAW
)
SELECT COUNT(CASE WHEN LAT_TEXTO IS NULL THEN 1 END) AS LAT_FALTANTES,
       COUNT(CASE WHEN LON_TEXTO IS NULL THEN 1 END) AS LON_FALTANTES,
       COUNT(CASE WHEN LAT_TEXTO IS NOT NULL AND LAT_NUM IS NULL
                  THEN 1 END) AS LAT_CONVERSION_INVALIDA,
       COUNT(CASE WHEN LON_TEXTO IS NOT NULL AND LON_NUM IS NULL
                  THEN 1 END) AS LON_CONVERSION_INVALIDA,
       COUNT(CASE WHEN LAT_NUM NOT BETWEEN -90 AND 90
                  THEN 1 END) AS LAT_FUERA_RANGO,
       COUNT(CASE WHEN LON_NUM NOT BETWEEN -180 AND 180
                  THEN 1 END) AS LON_FUERA_RANGO,
       MIN(LAT_NUM) AS LAT_MINIMA, MAX(LAT_NUM) AS LAT_MAXIMA,
       MIN(LON_NUM) AS LON_MINIMA, MAX(LON_NUM) AS LON_MAXIMA
FROM COORDENADAS;

-- 11. Revisa VIOLATIONS faltantes, vacíos o espacios, longitud máxima y textos mayores a 4000
SELECT COUNT(CASE WHEN VIOLATIONS IS NULL THEN 1 END) AS VIOLATIONS_NULOS,
       COUNT(CASE WHEN VIOLATIONS IS NOT NULL
                       AND NVL(LENGTH(TRIM(VIOLATIONS)), 0) = 0
                  THEN 1 END) AS VACIOS_O_ESPACIOS,
       MAX(LENGTH(VIOLATIONS)) AS LONGITUD_MAXIMA,
       COUNT(CASE WHEN LENGTH(VIOLATIONS) > 4000
                  THEN 1 END) AS MAYORES_4000
FROM FOOD_INSPECTIONS_RAW;

-- 12. Cuenta licencias NULL y licencias con valor cero
SELECT COUNT(*) - COUNT(LICENSE_NUMBER) AS LICENCIAS_NULAS,
       COUNT(CASE WHEN LICENSE_NUMBER = 0 THEN 1 END) AS LICENCIAS_CERO
FROM FOOD_INSPECTIONS_RAW;
