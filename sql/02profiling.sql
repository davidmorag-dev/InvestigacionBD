       MIN(LAT_NUM) AS LAT_MINIMA, MAX(LAT_NUM) AS LAT_MAXIMA,
       MIN(LON_NUM) AS LON_MINIMA, MAX(LON_NUM) AS LON_MAXIMA
FROM NUMEROS;

