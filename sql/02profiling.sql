    UNION ALL
    SELECT 'ZIP' AS COLUMNA, ZIP AS VALOR
    FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'RESULTS' AS COLUMNA, RESULTS AS VALOR
    FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'RISK' AS COLUMNA, RISK AS VALOR
    FROM FOOD_INSPECTIONS_RAW
), FRECUENCIAS AS (
    SELECT COLUMNA, VALOR, UPPER(TRIM(VALOR)) AS VALOR_NORMALIZADO,
           COUNT(*) AS CANTIDAD
