-- Agrupa las violaciones por longitud para detectar textos inusualmente largos
SELECT
    CASE
        WHEN VIOLATIONS IS NULL THEN 'SIN TEXTO'
        WHEN LENGTH(VIOLATIONS) <= 100 THEN '0-100 caracteres'
        WHEN LENGTH(VIOLATIONS) <= 500 THEN '101-500 caracteres'
        WHEN LENGTH(VIOLATIONS) <= 1000 THEN '501-1000 caracteres'
        ELSE 'Más de 1000 caracteres'
    END AS RANGO_LONGITUD,
    COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
GROUP BY
    CASE
        WHEN VIOLATIONS IS NULL THEN 'SIN TEXTO'
        WHEN LENGTH(VIOLATIONS) <= 100 THEN '0-100 caracteres'
        WHEN LENGTH(VIOLATIONS) <= 500 THEN '101-500 caracteres'
        WHEN LENGTH(VIOLATIONS) <= 1000 THEN '501-1000 caracteres'
        ELSE 'Más de 1000 caracteres'
    END
ORDER BY CANTIDAD DESC;

-- Cuenta cuántos tipos diferentes de establecimiento existen en FACILITY_TYPE
