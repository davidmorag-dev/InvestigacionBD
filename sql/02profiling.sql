-- Identifica el rango de fechas de las inspecciones registradas
SELECT
    MIN(INSPECTION_DATE) AS FECHA_MAS_ANTIGUA,
    MAX(INSPECTION_DATE) AS FECHA_MAS_RECIENTE
FROM FOOD_INSPECTIONS_RAW;


-- Comprueba si existen latitudes y longitudes fuera
-- de los rangos geográficos válidos.
SELECT
    COUNT(*) AS COORDENADAS_INVALIDAS
FROM FOOD_INSPECTIONS_RAW
WHERE
    (LATITUDE IS NOT NULL AND
        (VALIDATE_CONVERSION(LATITUDE AS NUMBER) = 0
         OR TO_NUMBER(LATITUDE DEFAULT NULL ON CONVERSION ERROR) < -90
         OR TO_NUMBER(LATITUDE DEFAULT NULL ON CONVERSION ERROR) > 90))
    OR
    (LONGITUDE IS NOT NULL AND
        (VALIDATE_CONVERSION(LONGITUDE AS NUMBER) = 0
         OR TO_NUMBER(LONGITUDE DEFAULT NULL ON CONVERSION ERROR) < -180
         OR TO_NUMBER(LONGITUDE DEFAULT NULL ON CONVERSION ERROR) > 180));