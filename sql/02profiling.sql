       COUNT(CASE WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) > 0
                       AND REGEXP_LIKE(VIOLATIONS, '^[[:space:]]*$', 'c')
                  THEN 1 END) AS SOLO_BLANCOS,
       MAX(DBMS_LOB.GETLENGTH(VIOLATIONS)) AS LONGITUD_MAXIMA,
       COUNT(CASE WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) > 4000 THEN 1 END)
           AS TEXTOS_MAYORES_4000
FROM FOOD_INSPECTIONS_RAW;

-- P30. Casos con las descripciones mas largas
-- Muestra los 20 textos mas largos con ID, longitud, inicio y final.
-- Las vistas previas son parciales; NO sustituyen la longitud completa.
-- El ID 2617205 es el maximo del CSV revisado y debe contrastarse.
SELECT INSPECTION_ID, DBA_NAME, RESULTS,
       DBMS_LOB.GETLENGTH(VIOLATIONS) AS LONGITUD_CARACTERES,
       DBMS_LOB.SUBSTR(VIOLATIONS, 250, 1) AS INICIO_TEXTO,
       DBMS_LOB.SUBSTR(VIOLATIONS, 250,
           GREATEST(1, DBMS_LOB.GETLENGTH(VIOLATIONS) - 249)) AS FINAL_TEXTO
FROM FOOD_INSPECTIONS_RAW
WHERE VIOLATIONS IS NOT NULL
ORDER BY LONGITUD_CARACTERES DESC, INSPECTION_ID, ROWID
FETCH FIRST 20 ROWS ONLY;

-- P31. Distribucion de longitud de VIOLATIONS
-- Conserva el analisis original por intervalos y agrega un intervalo
-- superior a 4.000 para justificar el uso de CLOB con resultados medibles.
WITH LONGITUDES AS (
    SELECT CASE
        WHEN VIOLATIONS IS NULL THEN 0
        WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) <= 100 THEN 1
        WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) <= 500 THEN 2
        WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) <= 1000 THEN 3
        WHEN DBMS_LOB.GETLENGTH(VIOLATIONS) <= 4000 THEN 4
        ELSE 5
    END AS ORDEN_RANGO
    FROM FOOD_INSPECTIONS_RAW
)
SELECT ORDEN_RANGO, CASE ORDEN_RANGO
    WHEN 0 THEN 'NULL' WHEN 1 THEN '0-100 caracteres'
    WHEN 2 THEN '101-500 caracteres' WHEN 3 THEN '501-1000 caracteres'
    WHEN 4 THEN '1001-4000 caracteres' ELSE 'Mas de 4000 caracteres'
    END AS RANGO_LONGITUD, COUNT(*) AS CANTIDAD
FROM LONGITUDES
GROUP BY ORDEN_RANGO
ORDER BY ORDEN_RANGO;

-- P32. Ausencia de VIOLATIONS segun RESULTS
-- Permite investigar si el texto faltante varia por resultado.
-- La asociacion no demuestra que un NULL signifique ausencia de infracciones.
SELECT RESULTS, COUNT(*) AS TOTAL_RESULTADO,
       COUNT(CASE WHEN VIOLATIONS IS NULL THEN 1 END) AS VIOLATIONS_NULOS,
       COUNT(CASE WHEN VIOLATIONS IS NOT NULL
                       AND (DBMS_LOB.GETLENGTH(VIOLATIONS) = 0
                            OR REGEXP_LIKE(VIOLATIONS, '^[[:space:]]*$', 'c'))
                  THEN 1 END) AS BLANCOS_O_VACIOS,
       ROUND(COUNT(CASE WHEN VIOLATIONS IS NULL THEN 1 END)
             * 100 / NULLIF(COUNT(*), 0), 2) AS PORCENTAJE_NULOS
FROM FOOD_INSPECTIONS_RAW
GROUP BY RESULTS
ORDER BY TOTAL_RESULTADO DESC, RESULTS;

-- P33. Diagnostico de LICENSE_NUMBER
-- Cuenta licencias NULL, cero y negativas por separado.
-- Cero no se considera automaticamente una licencia valida ni se reemplaza.
-- El CSV revisado tuvo 19 vacios y 837 ceros; confirmar en Oracle.
SELECT COUNT(*) AS TOTAL_REGISTROS,
       COUNT(CASE WHEN LICENSE_NUMBER IS NULL THEN 1 END) AS LICENCIAS_NULAS,
       COUNT(CASE WHEN LICENSE_NUMBER = 0 THEN 1 END) AS LICENCIAS_CERO,
       COUNT(CASE WHEN LICENSE_NUMBER < 0 THEN 1 END) AS LICENCIAS_NEGATIVAS,
       COUNT(DISTINCT LICENSE_NUMBER) AS LICENCIAS_DISTINTAS_NO_NULAS,
       MIN(LICENSE_NUMBER) AS LICENCIA_MINIMA,
       MAX(LICENSE_NUMBER) AS LICENCIA_MAXIMA
FROM FOOD_INSPECTIONS_RAW;

-- P34. Ejemplos de licencias NULL o no positivas
-- Muestra registros para investigar antes de usar LICENSE_NUMBER como
-- identificador de establecimiento. No decide imputacion ni eliminacion.
SELECT INSPECTION_ID, DBA_NAME, LICENSE_NUMBER, ADDRESS, CITY, ZIP,
       TO_CHAR(INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA, INSPECTION_TYPE, RESULTS
FROM FOOD_INSPECTIONS_RAW
WHERE LICENSE_NUMBER IS NULL OR LICENSE_NUMBER <= 0
ORDER BY INSPECTION_ID, ROWID
FETCH FIRST 50 ROWS ONLY;
