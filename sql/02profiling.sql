       COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
GROUP BY RISK
ORDER BY CANTIDAD DESC, RISK;

-- 7. Revisa categorías y frecuencias de FACILITY_TYPE
SELECT FACILITY_TYPE, UPPER(TRIM(FACILITY_TYPE)) AS VALOR_COMPARACION,
