-- 1. Verifica total de registros, IDs únicos, nulos y repeticiones
SELECT COUNT(*) AS TOTAL_REGISTROS,
       COUNT(DISTINCT INSPECTION_ID) AS ID_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS ID_NULOS,
       COUNT(INSPECTION_ID) - COUNT(DISTINCT INSPECTION_ID) AS REPETICIONES_ID
FROM FOOD_INSPECTIONS_RAW;

-- 2. Revisa valores NULL y textos con solo espacios en columnas de texto
WITH TEXTOS AS (
    SELECT 'DBA_NAME' AS COLUMNA, DBA_NAME AS VALOR FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'AKA_NAME', AKA_NAME FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'FACILITY_TYPE', FACILITY_TYPE FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'RISK', RISK FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'ADDRESS', ADDRESS FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'CITY', CITY FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'STATE', STATE FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'ZIP', ZIP FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'INSPECTION_TYPE', INSPECTION_TYPE FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'RESULTS', RESULTS FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'LATITUDE', LATITUDE FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'LONGITUDE', LONGITUDE FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'LOCATION', LOCATION FROM FOOD_INSPECTIONS_RAW
)
SELECT COLUMNA, COUNT(*) - COUNT(VALOR) AS NULOS,
       COUNT(CASE WHEN VALOR IS NOT NULL AND TRIM(VALOR) IS NULL
                  THEN 1 END) AS SOLO_ESPACIOS
FROM TEXTOS
GROUP BY COLUMNA
ORDER BY COLUMNA;

-- 3. Obtiene la fecha mínima, máxima y fechas NULL
SELECT TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA,
       COUNT(*) - COUNT(INSPECTION_DATE) AS FECHAS_NULAS
FROM FOOD_INSPECTIONS_RAW;

-- 4. Contrasta las fechas de los IDs 67757 y 2644019 con el CSV
WITH REFERENCIA AS (
    SELECT 67757 AS INSPECTION_ID, DATE '2010-01-04' AS FECHA_CSV FROM DUAL
    UNION ALL
    SELECT 2644019, DATE '2026-10-09' FROM DUAL
)
SELECT c.INSPECTION_ID,
       TO_CHAR(c.FECHA_CSV, 'YYYY-MM-DD') AS FECHA_CSV,
       TO_CHAR(r.INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA_ORACLE,
       CASE
           WHEN r.INSPECTION_ID IS NULL THEN 'ID AUSENTE'
           WHEN r.INSPECTION_DATE IS NULL THEN 'FECHA NULA'
           WHEN TRUNC(r.INSPECTION_DATE) = c.FECHA_CSV THEN 'COINCIDE'
           ELSE 'REVISAR'
       END AS VALIDACION
FROM REFERENCIA c
LEFT JOIN FOOD_INSPECTIONS_RAW r ON r.INSPECTION_ID = c.INSPECTION_ID
ORDER BY c.INSPECTION_ID;

-- 5. Revisa categorías y frecuencias de RESULTS
SELECT RESULTS, UPPER(TRIM(RESULTS)) AS VALOR_COMPARACION,
       COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW
GROUP BY RESULTS
ORDER BY CANTIDAD DESC, RESULTS;

-- 6. Revisa categorías y frecuencias de RISK, incluyendo All
