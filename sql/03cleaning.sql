-- 1. Crea CLEAN con las 17 columnas y solo las transformaciones aprobadas.
CREATE TABLE FOOD_INSPECTIONS_CLEAN AS
SELECT INSPECTION_ID,
       DBA_NAME,
       AKA_NAME,
       LICENSE_NUMBER,
       UPPER(TRIM(FACILITY_TYPE)) AS FACILITY_TYPE,
       RISK,
       TRIM(ADDRESS) AS ADDRESS,
       CITY,
       STATE,
       ZIP,
       INSPECTION_DATE,
       UPPER(TRIM(INSPECTION_TYPE)) AS INSPECTION_TYPE,
       RESULTS,
       VIOLATIONS,
       TO_NUMBER(REPLACE(TRIM(LATITUDE), ',', '.'),
                 '999D999999999999999',
                 'NLS_NUMERIC_CHARACTERS=''.,''') AS LATITUDE,
       TO_NUMBER(REPLACE(TRIM(LONGITUDE), ',', '.'),
                 '999D999999999999999',
                 'NLS_NUMERIC_CHARACTERS=''.,''') AS LONGITUDE,
       LOCATION
FROM FOOD_INSPECTIONS_RAW;

-- 2. Compara filas, IDs distintos e IDs NULL antes y despues.
SELECT 'RAW' AS TABLA, COUNT(*) AS REGISTROS,
       COUNT(DISTINCT INSPECTION_ID) AS ID_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS ID_NULOS
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(*), COUNT(DISTINCT INSPECTION_ID),
       COUNT(*) - COUNT(INSPECTION_ID)
FROM FOOD_INSPECTIONS_CLEAN;

-- 3. Compara direcciones NULL y formadas unicamente por espacios.
SELECT 'RAW' AS TABLA, COUNT(*) - COUNT(ADDRESS) AS ADDRESS_NULOS,
       COUNT(CASE WHEN ADDRESS IS NOT NULL AND TRIM(ADDRESS) IS NULL
                  THEN 1 END) AS ADDRESS_SOLO_ESPACIOS
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(*) - COUNT(ADDRESS),
       COUNT(CASE WHEN ADDRESS IS NOT NULL AND TRIM(ADDRESS) IS NULL
                  THEN 1 END)
FROM FOOD_INSPECTIONS_CLEAN;

-- 4. Compara las categorias de establecimiento y tipo de inspeccion.
SELECT 'RAW' AS TABLA,
       COUNT(DISTINCT FACILITY_TYPE) AS FACILITY_DISTINTOS,
       COUNT(DISTINCT INSPECTION_TYPE) AS INSPECTION_DISTINTOS
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(DISTINCT FACILITY_TYPE),
       COUNT(DISTINCT INSPECTION_TYPE)
FROM FOOD_INSPECTIONS_CLEAN;

-- 5. Compara coordenadas NULL, minimos, maximos y valores fuera de rango.
WITH COORDENADAS AS (
    SELECT 'RAW' AS TABLA,
           TO_NUMBER(REPLACE(TRIM(LATITUDE), ',', '.'),
                     '999D999999999999999',
                     'NLS_NUMERIC_CHARACTERS=''.,''') AS LATITUDE,
           TO_NUMBER(REPLACE(TRIM(LONGITUDE), ',', '.'),
                     '999D999999999999999',
                     'NLS_NUMERIC_CHARACTERS=''.,''') AS LONGITUDE
    FROM FOOD_INSPECTIONS_RAW
    UNION ALL
    SELECT 'CLEAN', LATITUDE, LONGITUDE
    FROM FOOD_INSPECTIONS_CLEAN
)
SELECT TABLA,
       COUNT(*) - COUNT(LATITUDE) AS LAT_NULOS,
       COUNT(*) - COUNT(LONGITUDE) AS LON_NULOS,
       MIN(LATITUDE) AS LAT_MINIMA, MAX(LATITUDE) AS LAT_MAXIMA,
       MIN(LONGITUDE) AS LON_MINIMA, MAX(LONGITUDE) AS LON_MAXIMA,
       COUNT(CASE WHEN LATITUDE NOT BETWEEN -90 AND 90
                  THEN 1 END) AS LAT_FUERA_RANGO,
       COUNT(CASE WHEN LONGITUDE NOT BETWEEN -180 AND 180
                  THEN 1 END) AS LON_FUERA_RANGO
FROM COORDENADAS
GROUP BY TABLA
ORDER BY TABLA DESC;

-- 6. Compara VIOLATIONS NULL, longitud maxima y textos mayores a 4000.
SELECT 'RAW' AS TABLA,
       COUNT(CASE WHEN VIOLATIONS IS NULL THEN 1 END) AS VIOLATIONS_NULOS,
       MAX(LENGTH(VIOLATIONS)) AS LONGITUD_MAXIMA,
       COUNT(CASE WHEN LENGTH(VIOLATIONS) > 4000 THEN 1 END) AS MAYORES_4000
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(CASE WHEN VIOLATIONS IS NULL THEN 1 END),
       MAX(LENGTH(VIOLATIONS)),
       COUNT(CASE WHEN LENGTH(VIOLATIONS) > 4000 THEN 1 END)
FROM FOOD_INSPECTIONS_CLEAN;

-- 7. Confirma las 17 columnas, las coordenadas NUMBER y VIOLATIONS CLOB.
SELECT TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('FOOD_INSPECTIONS_RAW', 'FOOD_INSPECTIONS_CLEAN')
ORDER BY TABLE_NAME DESC, COLUMN_ID;

-- 8. Compara licencias, RISK All y fechas que se conservaron sin cambios.
SELECT 'RAW' AS TABLA,
       COUNT(*) - COUNT(LICENSE_NUMBER) AS LICENCIAS_NULAS,
       COUNT(CASE WHEN LICENSE_NUMBER = 0 THEN 1 END) AS LICENCIAS_CERO,
       COUNT(CASE WHEN RISK = 'All' THEN 1 END) AS RISK_ALL,
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(*) - COUNT(LICENSE_NUMBER),
       COUNT(CASE WHEN LICENSE_NUMBER = 0 THEN 1 END),
       COUNT(CASE WHEN RISK = 'All' THEN 1 END),
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD'),
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD')
FROM FOOD_INSPECTIONS_CLEAN;
