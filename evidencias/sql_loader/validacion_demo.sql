-- 1. Verifica las 500 filas, IDs, fechas y VIOLATIONS de la muestra
SELECT COUNT(*) AS TOTAL, COUNT(DISTINCT INSPECTION_ID) AS IDS_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS IDS_NULOS,
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA,
       MAX(LENGTH(VIOLATIONS)) AS VIOLATIONS_MAXIMO,
       SUM(CASE WHEN LENGTH(VIOLATIONS) > 4000 THEN 1 ELSE 0 END) AS MAYORES_4000,
       SUM(CASE WHEN VIOLATIONS IS NULL THEN 1 ELSE 0 END) AS VIOLATIONS_NULOS
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST;

-- 2. Busca IDs de la muestra ausentes en RAW
SELECT COUNT(*) AS IDS_AUSENTES_EN_RAW
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST t
WHERE NOT EXISTS (SELECT 1 FROM FOOD_INSPECTIONS_RAW r WHERE r.INSPECTION_ID = t.INSPECTION_ID);

-- 3. Compara el contenido de las 17 columnas por ID, incluido VIOLATIONS completo
SELECT COUNT(*) AS IDS_COMPARADOS,
       SUM(DECODE(r.DBA_NAME, t.DBA_NAME, 0, 1)) AS DBA_DIF,
       SUM(DECODE(r.AKA_NAME, t.AKA_NAME, 0, 1)) AS AKA_DIF,
       SUM(DECODE(r.LICENSE_NUMBER, t.LICENSE_NUMBER, 0, 1)) AS LICENSE_DIF,
       SUM(DECODE(r.FACILITY_TYPE, t.FACILITY_TYPE, 0, 1)) AS FACILITY_DIF,
       SUM(DECODE(r.RISK, t.RISK, 0, 1)) AS RISK_DIF,
       SUM(DECODE(r.ADDRESS, t.ADDRESS, 0, 1)) AS ADDRESS_DIF,
       SUM(DECODE(r.CITY, t.CITY, 0, 1)) AS CITY_DIF,
       SUM(DECODE(r.STATE, t.STATE, 0, 1)) AS STATE_DIF,
       SUM(DECODE(r.ZIP, t.ZIP, 0, 1)) AS ZIP_DIF,
       SUM(DECODE(r.INSPECTION_DATE, t.INSPECTION_DATE, 0, 1)) AS DATE_DIF,
       SUM(DECODE(r.INSPECTION_TYPE, t.INSPECTION_TYPE, 0, 1)) AS TYPE_DIF,
       SUM(DECODE(r.RESULTS, t.RESULTS, 0, 1)) AS RESULTS_DIF,
       SUM(CASE WHEN r.VIOLATIONS IS NULL AND t.VIOLATIONS IS NULL THEN 0
                WHEN r.VIOLATIONS IS NULL OR t.VIOLATIONS IS NULL THEN 1
                WHEN DBMS_LOB.COMPARE(r.VIOLATIONS, t.VIOLATIONS) = 0 THEN 0
                ELSE 1 END) AS VIOLATIONS_DIF,
       SUM(DECODE(r.LATITUDE, t.LATITUDE, 0, 1)) AS LATITUDE_DIF,
       SUM(DECODE(r.LONGITUDE, t.LONGITUDE, 0, 1)) AS LONGITUDE_DIF,
       SUM(DECODE(r.LOCATION, t.LOCATION, 0, 1)) AS LOCATION_DIF
FROM FOOD_INSPECTIONS_RAW r
JOIN FOOD_INSPECTIONS_RAW_LOADER_TEST t ON t.INSPECTION_ID = r.INSPECTION_ID;

-- 4. Muestra tres textos largos y comprueba que coinciden completos con RAW
SELECT t.INSPECTION_ID, LENGTH(t.VIOLATIONS) AS LONGITUD_TEST,
       LENGTH(r.VIOLATIONS) AS LONGITUD_RAW,
       DBMS_LOB.COMPARE(r.VIOLATIONS, t.VIOLATIONS) AS DIFERENCIA_CLOB
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST t
JOIN FOOD_INSPECTIONS_RAW r ON r.INSPECTION_ID = t.INSPECTION_ID
ORDER BY LENGTH(t.VIOLATIONS) DESC NULLS LAST
FETCH FIRST 3 ROWS ONLY;

-- 5. Confirma los conteos de las fuentes oficiales despues de la demo
SELECT 'RAW' AS FUENTE, COUNT(*) AS TOTAL FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'CLEAN', COUNT(*) FROM FOOD_INSPECTIONS_CLEAN
UNION ALL
SELECT 'SCIENCE', COUNT(*) FROM FOOD_INSPECTIONS_SCIENCE;

