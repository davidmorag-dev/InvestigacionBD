-- 1. Compara total, IDs, fechas y longitudes completas de VIOLATIONS
SELECT 'RAW' AS TABLA, COUNT(*) AS TOTAL,
       COUNT(DISTINCT INSPECTION_ID) AS IDS_DISTINTOS,
       COUNT(*) - COUNT(INSPECTION_ID) AS IDS_NULOS,
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MINIMA,
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD') AS FECHA_MAXIMA,
       MAX(LENGTH(VIOLATIONS)) AS VIOLATIONS_MAXIMO,
       SUM(CASE WHEN LENGTH(VIOLATIONS) > 4000 THEN 1 ELSE 0 END) AS MAYORES_4000
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'LOADER_TEST', COUNT(*), COUNT(DISTINCT INSPECTION_ID),
       COUNT(*) - COUNT(INSPECTION_ID),
       TO_CHAR(MIN(INSPECTION_DATE), 'YYYY-MM-DD'),
       TO_CHAR(MAX(INSPECTION_DATE), 'YYYY-MM-DD'), MAX(LENGTH(VIOLATIONS)),
       SUM(CASE WHEN LENGTH(VIOLATIONS) > 4000 THEN 1 ELSE 0 END)
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST;

-- 2. Compara NULL principales y ADDRESS que contienen solamente espacios
SELECT 'RAW' AS TABLA,
       COUNT(*) - COUNT(AKA_NAME) AS AKA_NULOS,
       COUNT(*) - COUNT(LICENSE_NUMBER) AS LICENCIAS_NULAS,
       COUNT(*) - COUNT(FACILITY_TYPE) AS FACILITY_NULOS,
       COUNT(*) - COUNT(RISK) AS RISK_NULOS,
       COUNT(*) - COUNT(ADDRESS) AS ADDRESS_NULOS,
       SUM(CASE WHEN ADDRESS IS NOT NULL AND TRIM(ADDRESS) IS NULL THEN 1 ELSE 0 END) AS ADDRESS_ESPACIOS,
       COUNT(*) - COUNT(CITY) AS CITY_NULOS,
       COUNT(*) - COUNT(STATE) AS STATE_NULOS,
       COUNT(*) - COUNT(ZIP) AS ZIP_NULOS,
       COUNT(*) - COUNT(INSPECTION_TYPE) AS TYPE_NULOS,
       COUNT(*) - COUNT(VIOLATIONS) AS VIOLATIONS_NULOS,
       COUNT(*) - COUNT(LATITUDE) AS LATITUDE_NULOS,
       COUNT(*) - COUNT(LONGITUDE) AS LONGITUDE_NULOS,
       COUNT(*) - COUNT(LOCATION) AS LOCATION_NULOS
FROM FOOD_INSPECTIONS_RAW
UNION ALL
SELECT 'LOADER_TEST', COUNT(*) - COUNT(AKA_NAME), COUNT(*) - COUNT(LICENSE_NUMBER),
       COUNT(*) - COUNT(FACILITY_TYPE), COUNT(*) - COUNT(RISK), COUNT(*) - COUNT(ADDRESS),
       SUM(CASE WHEN ADDRESS IS NOT NULL AND TRIM(ADDRESS) IS NULL THEN 1 ELSE 0 END),
       COUNT(*) - COUNT(CITY), COUNT(*) - COUNT(STATE), COUNT(*) - COUNT(ZIP),
       COUNT(*) - COUNT(INSPECTION_TYPE), COUNT(*) - COUNT(VIOLATIONS),
       COUNT(*) - COUNT(LATITUDE), COUNT(*) - COUNT(LONGITUDE), COUNT(*) - COUNT(LOCATION)
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST;

-- 3. Compara la distribucion completa de RESULTS
SELECT 'RAW' AS TABLA, RESULTS, COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW GROUP BY RESULTS
UNION ALL
SELECT 'LOADER_TEST', RESULTS, COUNT(*)
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST GROUP BY RESULTS
ORDER BY RESULTS, TABLA;

-- 4. Busca IDs presentes en una tabla y ausentes en la otra
SELECT 'SOLO_RAW' AS DIFERENCIA, COUNT(*) AS CANTIDAD
FROM FOOD_INSPECTIONS_RAW r
WHERE NOT EXISTS (SELECT 1 FROM FOOD_INSPECTIONS_RAW_LOADER_TEST t WHERE t.INSPECTION_ID = r.INSPECTION_ID)
UNION ALL
SELECT 'SOLO_LOADER_TEST', COUNT(*)
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST t
WHERE NOT EXISTS (SELECT 1 FROM FOOD_INSPECTIONS_RAW r WHERE r.INSPECTION_ID = t.INSPECTION_ID);

-- 5. Cuenta diferencias por columna para cada ID, tratando dos NULL como iguales
SELECT COUNT(*) AS IDS_COMPARADOS,
       SUM(DECODE(r.DBA_NAME, t.DBA_NAME, 0, 1)) AS DBA_DIF,
       SUM(DECODE(r.AKA_NAME, t.AKA_NAME, 0, 1)) AS AKA_DIF,
       SUM(DECODE(r.LICENSE_NUMBER, t.LICENSE_NUMBER, 0, 1)) AS LICENSE_DIF,
       SUM(DECODE(r.FACILITY_TYPE, t.FACILITY_TYPE, 0, 1)) AS FACILITY_DIF,
       SUM(DECODE(r.RISK, t.RISK, 0, 1)) AS RISK_DIF,
       SUM(DECODE(r.ADDRESS, t.ADDRESS, 0, 1)) AS ADDRESS_DIF,
       SUM(DECODE(r.CITY, t.CITY, 0, 1)) AS CITY_DIF,
       SUM(DECODE(r.STATE, t.STATE, 0, 1)) AS STATE_DIF,
       SUM(DECODE(r.ZIP, t.ZIP, 0, 1)) AS ZIP_DIF,
       SUM(DECODE(r.INSPECTION_DATE, t.INSPECTION_DATE, 0, 1)) AS DATE_DIF,
       SUM(DECODE(r.INSPECTION_TYPE, t.INSPECTION_TYPE, 0, 1)) AS TYPE_DIF,
       SUM(DECODE(r.RESULTS, t.RESULTS, 0, 1)) AS RESULTS_DIF,
       SUM(CASE WHEN r.VIOLATIONS IS NULL AND t.VIOLATIONS IS NULL THEN 0
                WHEN r.VIOLATIONS IS NULL OR t.VIOLATIONS IS NULL THEN 1
                WHEN DBMS_LOB.COMPARE(r.VIOLATIONS, t.VIOLATIONS) = 0 THEN 0
                ELSE 1 END) AS VIOLATIONS_DIF,
       SUM(DECODE(r.LATITUDE, t.LATITUDE, 0, 1)) AS LATITUDE_DIF,
       SUM(DECODE(r.LONGITUDE, t.LONGITUDE, 0, 1)) AS LONGITUDE_DIF,
       SUM(DECODE(r.LOCATION, t.LOCATION, 0, 1)) AS LOCATION_DIF
FROM FOOD_INSPECTIONS_RAW r
JOIN FOOD_INSPECTIONS_RAW_LOADER_TEST t ON t.INSPECTION_ID = r.INSPECTION_ID;

-- 6. Muestra fechas sensibles, coordenadas y el inicio de VIOLATIONS sin recortar lo almacenado
SELECT 'RAW' AS TABLA, INSPECTION_ID, DBA_NAME,
       TO_CHAR(INSPECTION_DATE, 'YYYY-MM-DD') AS FECHA,
       LATITUDE, LONGITUDE, LENGTH(VIOLATIONS) AS LONGITUD_VIOLATIONS,
       DBMS_LOB.SUBSTR(VIOLATIONS, 120, 1) AS MUESTRA_VIOLATIONS
FROM FOOD_INSPECTIONS_RAW WHERE INSPECTION_ID IN (67757, 2644019)
UNION ALL
SELECT 'LOADER_TEST', INSPECTION_ID, DBA_NAME,
       TO_CHAR(INSPECTION_DATE, 'YYYY-MM-DD'), LATITUDE, LONGITUDE,
       LENGTH(VIOLATIONS), DBMS_LOB.SUBSTR(VIOLATIONS, 120, 1)
FROM FOOD_INSPECTIONS_RAW_LOADER_TEST WHERE INSPECTION_ID IN (67757, 2644019)
ORDER BY INSPECTION_ID, TABLA;

-- 7. Muestra las tres direcciones formadas por espacios y las cinco violaciones mas largas
SELECT r.INSPECTION_ID, LENGTH(r.ADDRESS) AS ESPACIOS_RAW,
       LENGTH(t.ADDRESS) AS ESPACIOS_TEST
FROM FOOD_INSPECTIONS_RAW r
JOIN FOOD_INSPECTIONS_RAW_LOADER_TEST t ON t.INSPECTION_ID = r.INSPECTION_ID
WHERE r.ADDRESS IS NOT NULL AND TRIM(r.ADDRESS) IS NULL;

SELECT r.INSPECTION_ID, LENGTH(r.VIOLATIONS) AS LONGITUD_RAW,
       LENGTH(t.VIOLATIONS) AS LONGITUD_TEST,
       DBMS_LOB.COMPARE(r.VIOLATIONS, t.VIOLATIONS) AS DIFERENCIA_CLOB
FROM FOOD_INSPECTIONS_RAW r
JOIN FOOD_INSPECTIONS_RAW_LOADER_TEST t ON t.INSPECTION_ID = r.INSPECTION_ID
ORDER BY LENGTH(r.VIOLATIONS) DESC NULLS LAST
FETCH FIRST 5 ROWS ONLY;

