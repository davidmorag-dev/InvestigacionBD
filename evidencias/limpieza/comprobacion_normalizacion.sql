-- 1. Compara los tipos de establecimiento antes y despues de UPPER(TRIM()).
SELECT COUNT(DISTINCT FACILITY_TYPE) AS DISTINTOS_ANTES,
       COUNT(DISTINCT UPPER(TRIM(FACILITY_TYPE))) AS DISTINTOS_DESPUES
FROM FOOD_INSPECTIONS_RAW;

-- 2. Compara los tipos de inspeccion antes y despues de UPPER(TRIM()).
SELECT COUNT(DISTINCT INSPECTION_TYPE) AS DISTINTOS_ANTES,
       COUNT(DISTINCT UPPER(TRIM(INSPECTION_TYPE))) AS DISTINTOS_DESPUES
FROM FOOD_INSPECTIONS_RAW;

-- 3. Muestra variantes de FACILITY_TYPE que se unificarian (hasta 30 filas).
SELECT UPPER(TRIM(FACILITY_TYPE)) AS NORMALIZADO,
       '[' || FACILITY_TYPE || ']' AS ORIGINAL,
       COUNT(*) AS REGISTROS
FROM FOOD_INSPECTIONS_RAW
WHERE UPPER(TRIM(FACILITY_TYPE)) IN (
    SELECT UPPER(TRIM(FACILITY_TYPE))
    FROM FOOD_INSPECTIONS_RAW
    GROUP BY UPPER(TRIM(FACILITY_TYPE))
    HAVING COUNT(DISTINCT FACILITY_TYPE) > 1
)
GROUP BY UPPER(TRIM(FACILITY_TYPE)), FACILITY_TYPE
ORDER BY NORMALIZADO, ORIGINAL
FETCH FIRST 30 ROWS ONLY;

-- 4. Muestra variantes de INSPECTION_TYPE que se unificarian (hasta 30 filas).
SELECT UPPER(TRIM(INSPECTION_TYPE)) AS NORMALIZADO,
       '[' || INSPECTION_TYPE || ']' AS ORIGINAL,
       COUNT(*) AS REGISTROS
FROM FOOD_INSPECTIONS_RAW
WHERE UPPER(TRIM(INSPECTION_TYPE)) IN (
    SELECT UPPER(TRIM(INSPECTION_TYPE))
    FROM FOOD_INSPECTIONS_RAW
    GROUP BY UPPER(TRIM(INSPECTION_TYPE))
    HAVING COUNT(DISTINCT INSPECTION_TYPE) > 1
)
GROUP BY UPPER(TRIM(INSPECTION_TYPE)), INSPECTION_TYPE
ORDER BY NORMALIZADO, ORIGINAL
FETCH FIRST 30 ROWS ONLY;
